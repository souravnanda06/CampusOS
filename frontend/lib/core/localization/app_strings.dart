  /// Translates a key or plain English text into the target language.
  /// Falls back smoothly to English and never returns an empty string or throws.
  static String tr(String keyOrText, {String? lang}) {
    if (keyOrText.isEmpty) return keyOrText;

    final targetLang = lang ?? LanguageProvider.instance.currentLanguage;
    final langMap = _localizedValues[targetLang] ?? _localizedValues['en']!;
    final enMap = _localizedValues['en']!;

    // 1. Direct match with original casing
    if (langMap.containsKey(keyOrText)) {
      return langMap[keyOrText]!;
    }

    // 2. Normalized snake_case match (e.g. "Quick Actions" -> "quick_actions")
    final normalized = keyOrText
        .trim()
        .toLowerCase()
        .replaceAll(RegExp(r'[\s\-·•&]+'), '_')
        .replaceAll(RegExp(r'[^\w_]'), '');

    if (langMap.containsKey(normalized)) {
      return langMap[normalized]!;
    }

    // 3. Fallback to English if translation is missing
    if (enMap.containsKey(keyOrText)) {
      return enMap[keyOrText]!;
    }
    if (enMap.containsKey(normalized)) {
      return enMap[normalized]!;
    }

    // 4. Return original text if not found
    return keyOrText;
  }
